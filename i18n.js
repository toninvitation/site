let currentLanguage = localStorage.getItem("toninvitation-language") || "pt";

function getTranslation(key) {
  return TRANSLATIONS[currentLanguage]?.[key] ?? TRANSLATIONS.pt[key] ?? key;
}

function setLanguage(language) {
  if (!TRANSLATIONS[language]) {
    language = "pt";
  }

  currentLanguage = language;
  localStorage.setItem("toninvitation-language", language);
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = getTranslation(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.placeholder = getTranslation(element.dataset.i18nPlaceholder);
  });

  updateLanguageSelector();

  window.dispatchEvent(
    new CustomEvent("languageChanged", {
      detail: {
        language
      }
    })
  );
}

function updateLanguageSelector() {
  document.querySelectorAll(".language-current").forEach(element => {
    element.textContent = `${TRANSLATIONS[currentLanguage].flag} ${currentLanguage.toUpperCase()}`;
  });

  document.querySelectorAll(".language-option").forEach(element => {
    element.classList.toggle(
      "active",
      element.dataset.language === currentLanguage
    );
  });
}

function createLanguageSelector() {
  document.querySelectorAll(".language-selector").forEach(selector => {
    const button = selector.querySelector(".language-current");

    button?.addEventListener("click", event => {
      event.stopPropagation();
      selector.classList.toggle("open");
    });

    selector.querySelectorAll(".language-option").forEach(option => {
      option.addEventListener("click", event => {
        event.stopPropagation();
        setLanguage(option.dataset.language);
        selector.classList.remove("open");
      });
    });
  });

  document.addEventListener("click", () => {
    document.querySelectorAll(".language-selector").forEach(selector => {
      selector.classList.remove("open");
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  createLanguageSelector();
  setLanguage(currentLanguage);
});
